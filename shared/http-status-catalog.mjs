const httpStatusCatalogByCode = new Map(httpStatusCatalog.map((entry) => [entry.code, entry]));

export const findHttpStatusCatalogEntry = (statusCode) => {
  const normalized = Number(statusCode);
  if (!Number.isInteger(normalized)) {
    return null;
  }
  return httpStatusCatalogByCode.get(normalized) ?? null;
};

export const isBodylessHttpStatus = (statusCode) =>
  findHttpStatusCatalogEntry(statusCode)?.bodyBehavior === HTTP_STATUS_BODY_BEHAVIOR.BODYLESS;
